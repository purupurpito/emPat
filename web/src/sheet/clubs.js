/**
 * Nombre de club → código oficial.
 * @type {Map<string, string>}
 */
const CLUB_CODES = new Map()

for (const row of CLUB_TABLE.split("\n")) {
    const bar = row.indexOf("|")
    if (bar > 0) {
        CLUB_CODES.set(row.slice(bar + 1), row.slice(0, bar))
    }
}

/**
 * Palabras que no distinguen a un club: formas jurídicas, palabras de vóley, artículos,
 * letras de equipo, colores, categorías y géneros.
 * @type {Set<string>}
 */
const STOP_WORDS = new Set(`
    CLUB CV C V CE AE AEE AEEI
    VOLEI VOLEIBOL VOLLEY VOLEY
    ASSOCIACIO ASSOCIACION ESPORTIU ESPORTIVA
    DE DEL LA EL LES ELS L D I Y
    A B E F G H
    VERD BLANC NEGRE GROC BLAU VERMELL TARONJA LILA ROSA
    JUNIOR JUVENIL CADET INFANTIL SENIOR MASCULI FEMENI`.trim().split(/\s+/))

/**
 * Palabras significativas de un nombre: sin tildes, en mayúsculas, solo letras y cifras y
 * sin las palabras vacías.
 * @param {unknown} name nombre
 * @returns {string[]}
 */
function keywords(name) {
    const plain = String(name || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    const words = plain.toUpperCase().replace(/[^A-Z0-9 ]/g, " ").split(/\s+/)
    return words.filter((word) => word && !STOP_WORDS.has(word))
}

/**
 * Propone la abreviatura de un equipo. Gana el club de la lista que comparte más palabras
 * significativas con el nombre; si dos códigos distintos empatan arriba no se elige ninguno
 * y se usan las tres primeras letras de la primera palabra. No consulta nada externo.
 * @param {unknown} name nombre del equipo
 * @returns {string} código, o cadena vacía si el nombre no tiene palabras significativas
 */
export function clubCode(name) {
    const wanted = keywords(name)
    if (wanted.length === 0) {
        return ""
    }
    let best = null
    let bestScore = 0
    let tied = false
    for (const [club, code] of CLUB_CODES) {
        const known = keywords(club)
        const score = wanted.filter((word) => known.includes(word)).length
        if (score > bestScore) {
            best = code
            bestScore = score
            tied = false
        } else if (score === bestScore && score > 0 && code !== best) {
            tied = true
        }
    }
    if (bestScore > 0 && !tied) {
        return best
    }
    return wanted[0].slice(0, 3)
}
